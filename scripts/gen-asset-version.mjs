#!/usr/bin/env node
/**
 * 自动生成静态资源版本号 + 构建信息（构建前运行）。
 * 原理：计算 public/styles/article.css 的内容指纹（md5 前 10 位），
 * 写入 edge-functions/api/_lib/asset-version.generated.js。
 * render-html.js 以 ?v=<指纹> 引用 CSS —— CSS 一变，URL 自动换新，
 * 绕开 EdgeOne /styles/* 的 1 小时 CDN 缓存，无需手动递增版本号。
 * 同时注入应用版本 / Next.js 版本 / 构建时间，供 /api/meta 展示。
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = join(root, 'public', 'styles', 'article.css');
const pkgPath = join(root, 'package.json');
const outPath = join(root, 'edge-functions', 'api', '_lib', 'asset-version.generated.js');

let hash = '0';
try {
  const css = readFileSync(cssPath);
  hash = createHash('md5').update(css).digest('hex').slice(0, 10);
  console.log(`[gen-asset-version] article.css ${css.length} bytes -> v${hash}`);
} catch (e) {
  console.warn('[gen-asset-version] article.css 未找到，使用 v0（构建将在 next build 复制 public/ 后正常）');
}

let appVersion = '0.0.0';
let nextVersion = '';
try {
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  appVersion = String(pkg.version || '0.0.0');
  const raw = (pkg.dependencies && pkg.dependencies.next) || (pkg.devDependencies && pkg.devDependencies.next) || '';
  nextVersion = String(raw).replace(/^[^\d]*/, '');
} catch { /* package.json 读取失败时保留默认值 */ }

const buildTime = new Date().toISOString();

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/gen-asset-version.mjs — 请勿手动编辑，构建前自动生成\n` +
  `export const ARTICLE_CSS_V = '${hash}';\n` +
  `export const APP_VERSION = '${appVersion}';\n` +
  `export const NEXT_VERSION = '${nextVersion}';\n` +
  `export const BUILD_TIME = '${buildTime}';\n`,
);